function makeExam(input: ExamInput): Exam {
  const {
    slug,
    code,
    name,
    providerSlug,
    level,
    category,
    summary,
    description,
    durationMinutes,
    questionCount,
    passingScore,
    languages,
    officialPriceInr,
    officialPriceUsd,
    retireAt,
    examUrl,
    audience,
    studyHours,
    skills,
    popularity,
    extraFaqs = [],
  } = input;

  const faqs: ExamFaq[] = [
    {
      question: `How long is the ${code} voucher valid?`,
      answer:
        "Vouchers we source are issued with a minimum 12-month validity from the date of delivery unless a specific expiry is shown on your offer. The expiry is confirmed in writing before you pay.",
    },
    {
      question: `Can I use a ${code} voucher in India?`,
      answer:
        "Yes. These exams are delivered through the provider's authorised testing network, which includes Pearson VUE test centres across India and online proctored delivery where the programme allows it.",
    },
    {
      question: "What happens if the voucher does not work?",
      answer:
        "We verify every code before delivery. If a code is rejected at the test centre or booking page, we replace it within one business day or refund you in full — your choice, not ours.",
    },
    ...extraFaqs,
  ];

  return {
    slug,
    code,
    name,
    providerSlug,
    level,
    category,
    summary,
    description:
      description ??
      `${name} (${code}) is a ${level}-level credential from ${
        providerSlug === "aws"
          ? "Amazon Web Services"
          : providerSlug === "microsoft"
            ? "Microsoft"
            : providerSlug === "google-cloud"
              ? "Google Cloud"
              : providerSlug === "cisco"
                ? "Cisco"
                : providerSlug === "comptia"
                  ? "CompTIA"
                  : providerSlug === "isc2"
                    ? "ISC2"
                    : providerSlug === "pmi"
                      ? "PMI"
                      : providerSlug === "hashicorp"
                        ? "HashiCorp"
                        : providerSlug === "cncf"
                          ? "CNCF"
                          : "Salesforce"
      }. It is designed for ${audience.toLowerCase()} and is recognised by employers across India and globally.`,
    durationMinutes,
    questionCount,
    passingScore,
    languages: languages ?? ["English", "Japanese", "Korean", "Simplified Chinese"],
    officialPriceInr,
    officialPriceUsd,
    retireAt,
    examUrl,
    audience,
    studyHours,
    skills,
    faqs,
    popularity,
  };
}

